def node(x,y,w,h,title,lines=(),kind='normal'):
 colors={'normal':('#eef3f1','#aebfbc','#18313e'),'focus':('#173440','#173440','#ffffff'),'green':('#e2efea','#087f79','#133a3a'),'orange':('#f6e9de','#c66a40','#523325')}
