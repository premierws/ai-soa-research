def text(x,y,t,size=23,color='#526c72',anchor='start'):
 return f'<text x="{x}" y="{y}" fill="{color}" font-size="{size}" text-anchor="{anchor}">{E(t)}</text>'
def arrow(x1,y1,x2,y2,label='',color='#087f79',dy=-12):
 s=f'<path d="M{x1},{y1} L{x2},{y2}" fill="none" stroke="{color}" stroke-width="3" marker-end="url(#ARR)"/>'
 if label:s+=text((x1+x2)/2,(y1+y2)/2+dy,label,22,color,'middle')
 return s
def svg(title,body,height=600):
 global serial
 serial+=1;key='arrow'+str(serial)
 return f'<svg class="diagram" viewBox="0 0 1600 {height}" role="img" aria-label="{E(title,quote=True)}" xmlns="http://www.w3.org/2000/svg"><defs><marker id="{key}" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path d="M0,0 L10,5 L0,10 Z" fill="#087f79"/></marker></defs>'+body.replace('#ARR','#'+key)+'</svg>'
def call(t):return '<div class="callout">'+t+'</div>'
