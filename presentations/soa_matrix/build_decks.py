def cards(items, cols='three'):
    return '<div class="grid '+cols+'">'+''.join(f'<div class="panel"><div class="num">{i+1:02}</div><h3>{a}</h3><p>{b}</p></div>' for i,(a,b) in enumerate(items))+'</div>'

def table(headers, rows, dense=False):
    return '<table'+(' class="dense"' if dense else '')+'><thead><tr>'+''.join(f'<th>{x}</th>' for x in headers)+'</tr></thead><tbody>'+''.join('<tr>'+''.join(f'<td>{x}</td>' for x in r)+'</tr>' for r in rows)+'</tbody></table>'

def flow(items):
    return '<div class="flow">'+'<i aria-hidden="true">→</i>'.join(f'<div><b>{a}</b><p>{b}</p></div>' for a,b in items)+'</div>'

def call(text, orange=False):
    return '<div class="callout'+(' orange' if orange else '')+'">'+text+'</div>'

def phases(items):
    return '<div class="timeline">'+''.join(f'<div class="phase"><div class="stage">STAGE {i+1:02}</div><h3>{a}</h3><p>{b}</p><div class="exit"><strong>推进条件</strong><br>{c}</div></div>' for i,(a,b,c) in enumerate(items))+'</div>'

def layers(items):
    return '<div class="stack">'+''.join(f'<div class="layer {"em" if active else ""}"><span class="label">{a}</span><b>{b}</b><small>{c}</small></div>' for a,b,c,active in items)+'</div>'

